-- =====================================================================
-- Brew & Bean: final exam e-commerce schema
-- Tables: roles, profiles, categories, products, orders, order_items
-- Functions: is_admin, handle_new_user (trigger), place_order (checkout)
-- RLS on every table, matching the permission table in the manual.
--
-- Run once in the Supabase SQL Editor. It replaces the products table
-- from the earlier price-filter activity.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------
drop table if exists public.order_items cascade;
drop table if exists public.orders cascade;
drop table if exists public.products cascade;
drop table if exists public.categories cascade;
drop table if exists public.profiles cascade;
drop table if exists public.roles cascade;

create table public.roles (
  id bigint generated by default as identity primary key,
  role varchar not null unique,
  created_at timestamptz not null default now(),
  encoded_by uuid references auth.users (id) on delete set null
);

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  email text,
  firstname text,
  role_id bigint references public.roles (id),
  lastname text
);

create table public.categories (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null unique check (length(trim(name)) > 0)
);

create table public.products (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null check (length(trim(name)) > 0),
  description text,
  stock smallint not null default 0 check (stock >= 0),
  image_url text,
  -- restrict: a category that still has products cannot be deleted
  category_id bigint not null references public.categories (id) on delete restrict,
  price real not null default 0 check (price >= 0)
);
create index products_price_idx on public.products (price);
create index products_category_idx on public.products (category_id);

create table public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  -- profiles.id is the auth.users id, so this also links to auth.users
  user_id uuid not null references public.profiles (id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'done', 'shipped', 'delivered', 'cancelled')),
  total numeric(12, 2) not null default 0 check (total >= 0)
);
create index orders_user_created_idx on public.orders (user_id, created_at desc);

create table public.order_items (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  order_id bigint not null references public.orders (id) on delete cascade,
  -- set null: past orders survive when a product is deleted
  product_id bigint references public.products (id) on delete set null,
  -- snapshot taken at checkout, so history stays accurate
  product_name text not null,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  quantity bigint not null check (quantity > 0)
);
create index order_items_order_idx on public.order_items (order_id);

-- ---------------------------------------------------------------------
-- 2. Functions and triggers
-- ---------------------------------------------------------------------

-- True when the signed-in user's profile has the 'admin' role.
-- security definer so it can read profiles/roles without tripping RLS.
create or replace function public.is_admin()
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  return exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = auth.uid() and r.role = 'admin'
  );
end;
$$;

-- Creates a profile for every new auth user. Every account starts as a
-- customer. Email sign-up sends firstname/lastname; Google sends
-- given_name/family_name (or full_name).
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  full_name text := coalesce(meta ->> 'full_name', meta ->> 'name', '');
begin
  insert into public.profiles (id, email, firstname, lastname, role_id)
  values (
    new.id,
    new.email,
    coalesce(meta ->> 'firstname', meta ->> 'given_name',
             nullif(split_part(full_name, ' ', 1), '')),
    coalesce(meta ->> 'lastname', meta ->> 'family_name',
             nullif(regexp_replace(full_name, '^\S+\s*', ''), '')),
    (select id from public.roles where role = 'customer')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Checkout. Runs as ONE transaction: if any line fails (missing product,
-- not enough stock), the exception rolls back the order, its items and
-- every stock change. Prices and names come from the products table,
-- never from the app. Input: [{"product_id": 1, "quantity": 2}, ...]
create or replace function public.place_order(items jsonb)
returns table (new_order_id bigint, order_total numeric)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_order bigint;
  v_total numeric(12, 2) := 0;
  v_line record;
  v_product record;
begin
  if v_user is null then
    raise exception 'You must be signed in to place an order'
      using errcode = '42501';
  end if;
  if public.is_admin() then
    raise exception 'Admin accounts cannot place orders'
      using errcode = '42501';
  end if;
  if items is null or jsonb_typeof(items) <> 'array'
     or jsonb_array_length(items) = 0 then
    raise exception 'Your cart is empty' using errcode = '22023';
  end if;

  insert into public.orders (user_id, status, total)
  values (v_user, 'pending', 0)
  returning id into v_order;

  -- Same product twice in the payload is merged; ordered by id so two
  -- checkouts lock rows in the same order (no deadlocks).
  for v_line in
    select (e ->> 'product_id')::bigint as product_id,
           sum((e ->> 'quantity')::int) as quantity
    from jsonb_array_elements(items) as e
    group by 1
    order by 1
  loop
    if v_line.quantity is null or v_line.quantity <= 0 then
      raise exception 'Invalid quantity in cart' using errcode = '22023';
    end if;

    select p.id, p.name, p.price, p.stock
      into v_product
      from public.products p
     where p.id = v_line.product_id
       for update;  -- lock the row until this transaction ends

    if not found then
      raise exception 'A product in your cart is no longer available'
        using errcode = 'P0002';
    end if;
    if v_product.stock < v_line.quantity then
      raise exception 'Only % left of "%"', v_product.stock, v_product.name
        using errcode = 'P0001';
    end if;

    insert into public.order_items
      (order_id, product_id, product_name, unit_price, quantity)
    values
      (v_order, v_product.id, v_product.name,
       round(v_product.price::numeric, 2), v_line.quantity);

    update public.products
       set stock = stock - v_line.quantity
     where id = v_product.id;

    v_total := v_total + round(v_product.price::numeric, 2) * v_line.quantity;
  end loop;

  -- Order stored successfully: mark it done.
  update public.orders set total = v_total, status = 'done' where id = v_order;

  return query select v_order, v_total;
end;
$$;

revoke execute on function public.handle_new_user() from public, anon, authenticated;
revoke execute on function public.place_order(jsonb) from public, anon;
grant execute on function public.place_order(jsonb) to authenticated;
revoke execute on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

-- ---------------------------------------------------------------------
-- 3. Table privileges (column level), on top of RLS
-- ---------------------------------------------------------------------
revoke all on public.roles, public.profiles, public.categories,
              public.products, public.orders, public.order_items
  from anon;

-- profiles: rows are created by the trigger only; users may change their
-- name but NEVER role_id, id or email.
revoke insert, update, delete on public.profiles from authenticated;
grant select on public.profiles to authenticated;
grant update (firstname, lastname) on public.profiles to authenticated;

-- roles: read only from the app
revoke insert, update, delete on public.roles from authenticated;
grant select on public.roles to authenticated;

grant select, insert, update, delete on public.categories to authenticated;
grant select, insert, update, delete on public.products to authenticated;

-- orders / order_items: written only by place_order(); admins may change
-- an order's status and nothing else.
revoke insert, update, delete on public.orders from authenticated;
grant select on public.orders to authenticated;
grant update (status) on public.orders to authenticated;
revoke insert, update, delete on public.order_items from authenticated;
grant select on public.order_items to authenticated;

-- ---------------------------------------------------------------------
-- 4. Row Level Security
-- Signed out (anon): no policies at all = no access.
-- ---------------------------------------------------------------------
alter table public.roles       enable row level security;
alter table public.profiles    enable row level security;
alter table public.categories  enable row level security;
alter table public.products    enable row level security;
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;

-- profiles: customer reads/updates own row; admin reads all
create policy "profiles read own" on public.profiles
  for select to authenticated
  using (id = (select auth.uid()));
create policy "profiles admin read all" on public.profiles
  for select to authenticated
  using ((select public.is_admin()));
create policy "profiles update own" on public.profiles
  for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- roles: read
create policy "roles read" on public.roles
  for select to authenticated
  using (true);

-- categories: everyone signed in reads; admin adds, edits, deletes
create policy "categories read" on public.categories
  for select to authenticated using (true);
create policy "create category" on public.categories
  for insert to authenticated with check ((select public.is_admin()));
create policy "update category" on public.categories
  for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "delete category" on public.categories
  for delete to authenticated using ((select public.is_admin()));

-- products: same as categories
create policy "products read" on public.products
  for select to authenticated using (true);
create policy "create product" on public.products
  for insert to authenticated with check ((select public.is_admin()));
create policy "update product" on public.products
  for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "delete product" on public.products
  for delete to authenticated using ((select public.is_admin()));

-- orders: customer reads own; admin reads all and updates status
create policy "orders read own" on public.orders
  for select to authenticated
  using (user_id = (select auth.uid()));
create policy "orders admin read all" on public.orders
  for select to authenticated
  using ((select public.is_admin()));
create policy "orders admin update status" on public.orders
  for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- order_items: customer reads items of own orders; admin reads all
create policy "order items read own" on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_id and o.user_id = (select auth.uid())
  ));
create policy "order items admin read all" on public.order_items
  for select to authenticated
  using ((select public.is_admin()));

